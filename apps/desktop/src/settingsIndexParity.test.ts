import { describe, expect, it } from "vitest";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { SETTINGS_SEARCH_INDEX } from "../../../packages/ui/src/lib/settingsSearchIndex";
import { SETTINGS_INDEX_ASYMMETRY } from "./settingsIndexParity.baseline";
import { REPO } from "./test-sourceTree";

/**
 * The settings search of both shells reads one generated index (settingsSearchIndex.test.ts). A setting that one
 * shell's page names and the other's does not is either a setting only one shell has, or a text the other shell's
 * page writes in a way the index did not see — the phone's folder rule "Change without asking" was the second
 * (plan "KI direkt schreiben": its line was written by a helper of the page). This compares the two shells' keys
 * area by area: what differs today is listed in `settingsIndexParity.baseline.ts`, and the list only shrinks. A new
 * difference fails here — bring the other shell along, or put the key into the baseline with the reason in the
 * commit (and, for a feature one shell lacks, an entry in the parity catalog).
 *
 * Rewrite the baseline after closing a difference: PLAINVA_WRITE_SETTINGS_PARITY=1 and this test.
 */

type Side = { desktopOnly: string[]; mobileOnly: string[] };

function asymmetry(): Record<string, Side> {
  const keys = { desktop: new Map<string, Set<string>>(), mobile: new Map<string, Set<string>>() };
  for (const entry of SETTINGS_SEARCH_INDEX) {
    const set = keys[entry.shell].get(entry.area) ?? new Set<string>();
    for (const key of [entry.card, entry.label, ...(entry.desc ?? []), ...(entry.info ?? [])]) if (key) set.add(key);
    keys[entry.shell].set(entry.area, set);
  }
  const out: Record<string, Side> = {};
  // Only areas both shells have: an area one shell lacks is the parity catalog's to say.
  for (const area of [...keys.desktop.keys()].filter((name) => keys.mobile.has(name)).sort()) {
    const desktop = keys.desktop.get(area)!;
    const mobile = keys.mobile.get(area)!;
    const side: Side = { desktopOnly: [...desktop].filter((key) => !mobile.has(key)).sort(), mobileOnly: [...mobile].filter((key) => !desktop.has(key)).sort() };
    if (side.desktopOnly.length || side.mobileOnly.length) out[area] = side;
  }
  return out;
}

function render(table: Record<string, Side>): string {
  const lines = Object.entries(table).map(
    ([area, side]) => `  ${JSON.stringify(area)}: {\n    desktopOnly: ${JSON.stringify(side.desktopOnly)},\n    mobileOnly: ${JSON.stringify(side.mobileOnly)},\n  },`,
  );
  return [
    "// GENERATED by apps/desktop/src/settingsIndexParity.test.ts (PLAINVA_WRITE_SETTINGS_PARITY=1) - it only shrinks.",
    "// The locale keys of the settings search index that one shell's pages name and the other's do not, by area.",
    "export const SETTINGS_INDEX_ASYMMETRY: Record<string, { desktopOnly: readonly string[]; mobileOnly: readonly string[] }> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

describe("the settings index of both shells", () => {
  it("names the same settings in both shells, but for the differences the baseline lists — and that list only shrinks", () => {
    const now = asymmetry();
    if (process.env.PLAINVA_WRITE_SETTINGS_PARITY === "1") writeFileSync(join(REPO, "apps/desktop/src/settingsIndexParity.baseline.ts"), render(now), "utf8");
    const added: string[] = [];
    const closed: string[] = [];
    for (const area of new Set([...Object.keys(now), ...Object.keys(SETTINGS_INDEX_ASYMMETRY)])) {
      for (const side of ["desktopOnly", "mobileOnly"] as const) {
        const known = new Set(SETTINGS_INDEX_ASYMMETRY[area]?.[side] ?? []);
        const found = new Set(now[area]?.[side] ?? []);
        for (const key of found) if (!known.has(key)) added.push(`${area} ${side}: ${key}`);
        for (const key of known) if (!found.has(key)) closed.push(`${area} ${side}: ${key}`);
      }
    }
    expect(added, "a setting stands in one shell's index only: bring the other shell along, or list it in the baseline").toEqual([]);
    expect(closed, "a difference was closed: shrink the baseline (PLAINVA_WRITE_SETTINGS_PARITY=1)").toEqual([]);
  });

  it("holds the folder rule's three questions in both shells", () => {
    for (const shell of ["desktop", "mobile"] as const) {
      const keys = SETTINGS_SEARCH_INDEX.filter((entry) => entry.shell === shell && entry.area === "aiVault").flatMap((entry) => [...(entry.desc ?? []), entry.label ?? ""]);
      expect(keys, shell).toEqual(expect.arrayContaining(["ai.policy.cloud", "ai.policy.web", "ai.policy.write"]));
    }
  });
});
